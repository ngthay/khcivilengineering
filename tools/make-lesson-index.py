"""
make-lesson-index.py
Writes js/lesson-index.js: the list of lessons of every course page,
used by the "View All" lists on the home page.

Run it from the website folder after adding, removing or renaming lessons:
    python tools/make-lesson-index.py
"""

import json
import re
from pathlib import Path

root = Path(__file__).resolve().parent.parent
TITLE = re.compile(r"title:\s*'((?:\\'|[^'])*)'")
courses = {}

for page in sorted(root.glob("*.html")):
    html = page.read_text(encoding="utf8")
    scripts = re.findall(r'<script src="(js/lessons/[^"]+\.js)"></script>', html)
    if not scripts:
        continue
    course_js = (root / scripts[0]).read_text(encoding="utf8")
    lessons = []
    for src in scripts[1:]:
        text = (root / src).read_text(encoding="utf8")
        head = text[text.index("lessons.push("):]
        lesson_id = re.search(r"id:\s*'([^']+)'", head).group(1)
        num = int(re.search(r"num:\s*(\d+)", head).group(1))
        title = TITLE.search(head).group(1).replace("\\'", "'")
        lessons.append([lesson_id, num, title])
    lessons.sort(key=lambda l: l[1])
    courses[page.name] = {
        "title": TITLE.search(course_js).group(1).replace("\\'", "'"),
        "lessons": lessons,
    }
    print(f"{page.name:22s} {len(lessons):3d} lessons")

blocks = []
for name, c in courses.items():
    rows = ",\n".join("      " + json.dumps(l, ensure_ascii=False) for l in c["lessons"])
    blocks.append(f'  "{name}": {{\n    "title": {json.dumps(c["title"], ensure_ascii=False)},\n'
                  f'    "lessons": [\n{rows}\n    ]\n  }}')
out = root / "js" / "lesson-index.js"
out.write_text(
    "/* Generated by tools/make-lesson-index.py - do not edit by hand.\n"
    "   Lessons of every course page, for the home page \"View All\" lists.\n"
    "   Each lesson: [id, number, title] */\n"
    "window.KCE_LESSONS = {\n" + ",\n".join(blocks) + "\n};\n",
    encoding="utf8",
)
print(f"\nwrote {out.relative_to(root)}")
